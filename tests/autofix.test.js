"use strict";
// Тесты автоправки: словарь, заглавные, знак в конце, запятые, мелочи.
const test = require("node:test");
const assert = require("node:assert/strict");
const { loadScripts } = require("./helpers");

const SS = loadScripts(["js/autofix.js"]);
const Autofix = SS.Autofix;

/** Короткая запись: применить все правила к русской фразе. */
function fix(text, options) {
  return Autofix.autofix(text, options);
}

// ---------------------------------------------------------------
// Примеры из задания: вход → выход
// ---------------------------------------------------------------

test("автоправка: «привет всем как дела» — без запятой и без вопроса", () => {
  // По правилам задания «как» не входит в список союзов, а вопрос
  // определяется по первому слову: «привет» — не вопросительное слово.
  // Поэтому честный результат — с точкой. Границы описаны в README.
  assert.equal(fix("привет всем как дела"), "Привет всем как дела.");
});

test("автоправка: «как дела» — вопрос", () => {
  assert.equal(fix("как дела"), "Как дела?");
});

test("автоправка: «я думаю что ты прав» — запятая перед «что»", () => {
  assert.equal(fix("я думаю что ты прав"), "Я думаю, что ты прав.");
});

test("автоправка: «потому что я устал» — в начале фразы без запятой", () => {
  assert.equal(fix("потому что я устал"), "Потому что я устал.");
});

test("автоправка: «я пришёл потому что ты позвал» — запятая перед союзом", () => {
  assert.equal(fix("я пришёл потому что ты позвал"), "Я пришёл, потому что ты позвал.");
});

test("автоправка: «это игра которая мне нравится» — запятая перед «которая»", () => {
  assert.equal(fix("это игра которая мне нравится"), "Это игра, которая мне нравится.");
});

test("автоправка: «хочу играть но надо работать» — запятая перед «но»", () => {
  assert.equal(fix("хочу играть но надо работать"), "Хочу играть, но надо работать.");
});

test("автоправка: «короче я ушёл» — запятая после вводного слова", () => {
  assert.equal(fix("короче я ушёл"), "Короче, я ушёл.");
});

test("автоправка: «пойдёшь ли ты» — вопрос из-за частицы «ли»", () => {
  assert.equal(fix("пойдёшь ли ты"), "Пойдёшь ли ты?");
});

test("автоправка: «ну что поехали» — без запятой перед «что»", () => {
  assert.equal(fix("ну что поехали"), "Ну что поехали.");
});

test("автоправка: словарь заменяет «твич» и «обс»", () => {
  assert.equal(fix("сегодня твич и обс"), "Сегодня Twitch и OBS.");
});

test("автоправка: свой словарь работает и меняет слова", () => {
  const dictionary = [{ from: "тг", to: "Telegram" }];
  assert.equal(fix("сегодня тг", { dictionary }), "Сегодня Telegram.");
});

test("автоправка: «привет. как дела» — заглавная во втором предложении", () => {
  assert.equal(fix("привет. как дела"), "Привет. Как дела?");
});

test("автоправка: уже правильная фраза не меняется", () => {
  assert.equal(fix("Привет, как дела?"), "Привет, как дела?");
  assert.equal(fix("Привет!"), "Привет!");
  assert.equal(fix("Привет…"), "Привет…");
});

test("автоправка: пустая строка и null остаются пустыми", () => {
  assert.equal(fix(""), "");
  assert.equal(fix(null), "");
  assert.equal(fix(undefined), "");
});

test("автоправка: двойные пробелы схлопываются", () => {
  assert.equal(fix("привет   всем"), "Привет всем.");
});

test("автоправка: числа не трогаются", () => {
  assert.equal(fix("в 2026 году"), "В 2026 году.");
  assert.equal(fix("2026"), "2026.");
});

test("автоправка: английский вопрос", () => {
  assert.equal(
    fix("what are you doing", { language: "en-US" }),
    "What are you doing?"
  );
});

test("автоправка: английская запятая перед but", () => {
  assert.equal(
    fix("i like it but not now", { language: "en-US" }),
    "I like it, but not now."
  );
});

// ---------------------------------------------------------------
// Правила включаются и выключаются по отдельности
// ---------------------------------------------------------------

test("правило словаря выключается", () => {
  const text = fix("сегодня твич", { rules: { dictionary: false } });
  assert.equal(text, "Сегодня твич.");
});

test("правило заглавной буквы выключается", () => {
  assert.equal(fix("как дела", { rules: { capitalize: false } }), "как дела?");
});

test("правило знака в конце выключается", () => {
  assert.equal(fix("как дела", { rules: { punctuation: false } }), "Как дела");
});

test("правило запятых выключается", () => {
  assert.equal(
    fix("я думаю что ты прав", { rules: { commas: false } }),
    "Я думаю что ты прав."
  );
});

test("правило мелочей выключается: лишние пробелы остаются", () => {
  assert.equal(
    fix("привет   всем", { rules: { cleanup: false } }),
    "Привет   всем."
  );
});

test("можно включить только знак в конце", () => {
  const rules = {
    dictionary: false,
    capitalize: false,
    commas: false,
    cleanup: false,
  };
  assert.equal(fix("как дела", { rules }), "как дела?");
});

test("неизвестные правила не включаются сами", () => {
  const rules = { dictionary: false, capitalize: false, punctuation: false, commas: false, cleanup: false };
  assert.equal(fix("  привет  всем ", { rules }), "  привет  всем ");
});

// ---------------------------------------------------------------
// Словарь: целые слова, регистр, фразы
// ---------------------------------------------------------------

test("словарь не трогает часть слова («обстановка»)", () => {
  assert.equal(fix("обстановка и обс"), "Обстановка и OBS.");
});

test("словарь не зависит от регистра", () => {
  assert.equal(fix("ТВИЧ"), "Twitch.");
  assert.equal(fix("Твич"), "Twitch.");
});

test("словарь умеет целые фразы", () => {
  const dictionary = [{ from: "ник зрителя", to: "luna_kot" }];
  assert.equal(fix("привет ник зрителя", { dictionary }), "Привет luna_kot.");
});

test("sanitizeDictionary отбрасывает пустые и мусорные пары", () => {
  const cleaned = Autofix.sanitizeDictionary([
    { from: "  обс  ", to: "OBS" },
    { from: "", to: "пусто" },
    { from: null, to: "нет" },
    "мусор",
    { to: "без было" },
  ]);
  assert.deepEqual(cleaned, [{ from: "обс", to: "OBS" }]);
});

test("словарь экспортируется в JSON и импортируется обратно", () => {
  const dictionary = [{ from: "твич", to: "Twitch" }];
  const json = Autofix.dictionaryToJson(dictionary);
  assert.match(json, /"from": "твич"/);
  const parsed = Autofix.dictionaryFromJson(json);
  assert.equal(parsed.ok, true);
  assert.deepEqual(parsed.dictionary, dictionary);
});

test("импорт битого JSON даёт понятную ошибку", () => {
  const parsed = Autofix.dictionaryFromJson("{это не json");
  assert.equal(parsed.ok, false);
  assert.match(parsed.error, /JSON/);
});

test("импорт файла без списка замен даёт понятную ошибку", () => {
  assert.equal(Autofix.dictionaryFromJson('{"что-то": 1}').ok, false);
});

// ---------------------------------------------------------------
// Запятые: осторожные правила
// ---------------------------------------------------------------

test("двойной запятой не бывает", () => {
  assert.equal(fix("я думаю, что ты прав"), "Я думаю, что ты прав.");
});

test("перед «если» после «а» запятая не ставится", () => {
  assert.equal(fix("а если пойдёт дождь"), "А если пойдёт дождь.");
});

test("в «то, что» запятая перед «что» не дублируется", () => {
  assert.equal(fix("то, что ты сказал"), "То, что ты сказал.");
});

test("перед союзом меньше двух слов — запятой нет", () => {
  assert.equal(fix("игра которая мне нравится"), "Игра которая мне нравится.");
});

test("союз в начале фразы не получает запятую", () => {
  assert.equal(fix("но я приду"), "Но я приду.");
  assert.equal(fix("если пойдёт дождь"), "Если пойдёт дождь.");
  // «Когда» — ещё и вопросительное слово: запятой нет, но знак вопроса да.
  assert.equal(fix("когда я приду домой"), "Когда я приду домой?");
});

test("вводное слово в начале фразы выделяется запятой", () => {
  assert.equal(fix("кстати я дома"), "Кстати, я дома.");
  assert.equal(fix("может быть пойдём"), "Может быть, пойдём.");
});

test("«однако» в начале фразы — без запятой, в середине — с запятой", () => {
  assert.equal(fix("однако он пришёл"), "Однако он пришёл.");
  assert.equal(fix("я устал однако пришёл"), "Я устал, однако пришёл.");
});

// ---------------------------------------------------------------
// Вопросы и мелочи
// ---------------------------------------------------------------

test("вопросительные слова в начале дают вопрос", () => {
  assert.equal(fix("где ты был"), "Где ты был?");
  assert.equal(fix("неужели это правда"), "Неужели это правда?");
  assert.equal(fix("сколько стоит"), "Сколько стоит?");
});

test("частица «ли» после первого слова даёт вопрос", () => {
  assert.equal(fix("ты придёшь ли"), "Ты придёшь ли?");
});

test("английское do в начале даёт вопрос", () => {
  assert.equal(fix("do you like it", { language: "en-US" }), "Do you like it?");
});

test("английское утверждение остаётся утверждением", () => {
  assert.equal(fix("i think it is fine", { language: "en-US" }), "I think it is fine.");
});

test("несколько предложений: заглавные и вопросы в каждом", () => {
  assert.equal(fix("привет! как ты? где был"), "Привет! Как ты? Где был?");
});

test("пробел перед запятой убирается, лишние пробелы — тоже", () => {
  assert.equal(fix("привет , как дела"), "Привет, как дела.");
});

test("буква «ё» не превращается в «е»", () => {
  assert.equal(fix("ещё раз"), "Ещё раз.");
});

test("знак в конце не добавляется повторно", () => {
  assert.equal(fix("как дела?"), "Как дела?");
  assert.equal(fix("привет!"), "Привет!");
});

test("isRussianQuestion и isEnglishQuestion — отдельные функции", () => {
  assert.equal(Autofix.isRussianQuestion("как дела"), true);
  assert.equal(Autofix.isRussianQuestion("я пришёл"), false);
  assert.equal(Autofix.isEnglishQuestion("what is it"), true);
  assert.equal(Autofix.isEnglishQuestion("i know"), false);
});

// ---------------------------------------------------------------
// Слова с дефисом: «как-то», «что-то», «где-то» — одно слово
// ---------------------------------------------------------------

test("слово с дефисом не считается вопросительным", () => {
  assert.equal(fix("как-то так"), "Как-то так.");
  assert.equal(fix("почему-то не работает"), "Почему-то не работает.");
  assert.equal(fix("как-нибудь потом"), "Как-нибудь потом.");
  assert.equal(fix("какой-то человек пришёл"), "Какой-то человек пришёл.");
});

test("часть слова с дефисом не даёт лишней запятой", () => {
  assert.equal(fix("я знаю что-то интересное"), "Я знаю что-то интересное.");
  assert.equal(fix("я видел это где-то"), "Я видел это где-то.");
  assert.equal(fix("он пришёл когда-то давно"), "Он пришёл когда-то давно.");
});

// ---------------------------------------------------------------
// Двойных запятых не бывает
// ---------------------------------------------------------------

test("вводное слово и союз рядом не дают двойной запятой", () => {
  assert.equal(fix("короче но я ушёл"), "Короче, но я ушёл.");
  assert.equal(fix("значит а он прав"), "Значит, а он прав.");
  assert.equal(fix("может быть но я ушёл"), "Может быть, но я ушёл.");
});

// ---------------------------------------------------------------
// Настоящие проверки исключений (запятая уже могла бы появиться)
// ---------------------------------------------------------------

test("«вот что», «ну что», «то что» — без запятой перед «что»", () => {
  assert.equal(fix("он сказал вот что"), "Он сказал вот что.");
  assert.equal(fix("я устал ну что пошли"), "Я устал ну что пошли.");
  assert.equal(fix("я знаю то что ты сказал"), "Я знаю то что ты сказал.");
});

test("«а если» и «но если» — без запятой перед «если»", () => {
  assert.equal(fix("он сказал а если дождь"), "Он сказал, а если дождь.");
  assert.equal(fix("я устал но если дождь"), "Я устал, но если дождь.");
});

// ---------------------------------------------------------------
// Остальные подчинительные союзы и английское because
// ---------------------------------------------------------------

test("запятые перед чтобы, когда, куда, хотя", () => {
  assert.equal(fix("он сказал чтобы я пришёл"), "Он сказал, чтобы я пришёл.");
  assert.equal(fix("я был там когда шёл дождь"), "Я был там, когда шёл дождь.");
  assert.equal(fix("я увидел куда он пошёл"), "Я увидел, куда он пошёл.");
  assert.equal(fix("я пришёл хотя устал"), "Я пришёл, хотя устал.");
});

test("запятая перед «так как» и «зато»", () => {
  assert.equal(fix("я устал так как много работал"), "Я устал, так как много работал.");
  assert.equal(fix("я устал зато пришёл"), "Я устал, зато пришёл.");
});

test("английское because получает запятую", () => {
  assert.equal(
    fix("i stayed home because it rained", { language: "en-US" }),
    "I stayed home, because it rained."
  );
});

// ---------------------------------------------------------------
// Знак в конце и кавычки
// ---------------------------------------------------------------

test("заглавная начинается и после многоточия", () => {
  assert.equal(fix("привет… как дела"), "Привет… Как дела?");
});

test("точка ставится после закрывающей кавычки", () => {
  assert.equal(fix("он сказал «привет»"), "Он сказал «привет».");
});

test("висячая запятая или двоеточие заменяются точкой", () => {
  assert.equal(fix("привет,"), "Привет.");
  assert.equal(fix("привет:"), "Привет.");
});

test("словарь принимает и массив, и объект с pairs", () => {
  // Пара не из словаря по умолчанию: иначе тест не заметил бы, что
  // объект {pairs} проигнорирован и взяты обычные замены.
  const pairs = [{ from: "тг", to: "Telegram" }];
  assert.equal(fix("тг", { dictionary: pairs }), "Telegram.");
  assert.equal(fix("тг", { dictionary: { pairs: pairs } }), "Telegram.");
});
